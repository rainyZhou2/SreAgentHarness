package domain

import "time"

type ThoughtKind string

const (
	ThoughtPlan         ThoughtKind = "plan"
	ThoughtObservation  ThoughtKind = "observation"
	ThoughtHypothesis   ThoughtKind = "hypothesis"
	ThoughtEvidence     ThoughtKind = "evidence"
	ThoughtDecision     ThoughtKind = "decision"
	ThoughtAction       ThoughtKind = "action"
	ThoughtVerification ThoughtKind = "verification"
	ThoughtReflection   ThoughtKind = "reflection"
	ThoughtConclusion   ThoughtKind = "conclusion"
)

type ThoughtStatus string

const (
	ThoughtUnknown    ThoughtStatus = "UNKNOWN"
	ThoughtUnverified ThoughtStatus = "UNVERIFIED"
	ThoughtVerified   ThoughtStatus = "VERIFIED"
	ThoughtRefuted    ThoughtStatus = "REFUTED"
	ThoughtOK         ThoughtStatus = "OK"
	ThoughtFailed     ThoughtStatus = "FAILED"
)

// ThoughtChain is the structured part of a decision: an explicit plan, the
// expected observation and the final verification/reflection. It is not
// provider-hidden reasoning.
type ThoughtChain struct {
	Plan         string        `json:"plan,omitempty"`
	Expected     string        `json:"expected_observation,omitempty"`
	Confidence   float64       `json:"confidence,omitempty"`
	Reflection   string        `json:"reflection,omitempty"`
	Verification *Verification `json:"verification,omitempty"`
	Structured   bool          `json:"structured,omitempty"`
}

type Verification struct {
	Expected string `json:"expected,omitempty"`
	Observed string `json:"observed,omitempty"`
	Verdict  string `json:"verdict,omitempty"`
}

// Thought is one node of the explicit decision trace. It is generated by the
// harness strategy; it never contains provider-hidden reasoning.
type Thought struct {
	ID         string         `json:"id,omitempty"`
	Seq        int            `json:"seq"`
	Kind       ThoughtKind    `json:"kind"`
	Summary    string         `json:"summary"`
	DetailRef  string         `json:"detail_ref,omitempty"`
	Status     ThoughtStatus  `json:"status,omitempty"`
	Confidence float64        `json:"confidence,omitempty"`
	Structured bool           `json:"structured,omitempty"`
	Attrs      map[string]any `json:"attrs,omitempty"`
	Refs       []ThoughtRef   `json:"refs,omitempty"`
}

// ThoughtRef links a thought to a capability, memory, evidence or artifact.
type ThoughtRef struct {
	Ref      string `json:"ref"`
	Relation string `json:"relation"`
}

// CapabilityRef records that a step used or considered a capability.
type CapabilityRef struct {
	Ref  string `json:"ref"`
	Role string `json:"role"` // used | considered
}

type CapabilityNode struct {
	TenantID  string         `json:"-"`
	Ref       string         `json:"ref"`
	Kind      string         `json:"kind"`
	Name      string         `json:"name"`
	Version   string         `json:"version,omitempty"`
	Owner     string         `json:"owner,omitempty"`
	Source    string         `json:"source,omitempty"`
	Risk      string         `json:"risk,omitempty"`
	Trust     string         `json:"trust,omitempty"`
	ServiceID string         `json:"service_id,omitempty"`
	Labels    map[string]any `json:"labels,omitempty"`
	SyncedAt  time.Time      `json:"synced_at"`
}

type CapabilityRelation struct {
	TenantID string         `json:"-"`
	SrcRef   string         `json:"src_ref"`
	DstRef   string         `json:"dst_ref"`
	Relation string         `json:"relation"`
	Source   string         `json:"source"`
	Weight   float64        `json:"weight"`
	Attrs    map[string]any `json:"attrs,omitempty"`
}

type GraphNode struct {
	Ref       string         `json:"ref"`
	Kind      string         `json:"kind"`
	Label     string         `json:"label"`
	Attrs     map[string]any `json:"attrs,omitempty"`
	UpdatedAt time.Time      `json:"updated_at,omitempty"`
}

type GraphEdge struct {
	Src      string         `json:"src"`
	Relation string         `json:"relation"`
	Dst      string         `json:"dst"`
	Source   string         `json:"source"`
	Weight   float64        `json:"weight"`
	Attrs    map[string]any `json:"attrs,omitempty"`
}

type Graph struct {
	Nodes     []GraphNode `json:"nodes"`
	Edges     []GraphEdge `json:"edges"`
	Truncated bool        `json:"truncated"`
}

// CapabilityNote is one capability-map line: a capability related to the
// active service plus its most recent verified lesson, if any.
type CapabilityNote struct {
	Node   CapabilityNode `json:"node"`
	Lesson string         `json:"lesson,omitempty"`
}

type MemoryShard struct {
	MemoryID string  `json:"memory_id"`
	ShardKey string  `json:"shard_key"`
	Weight   float64 `json:"weight"`
	Source   string  `json:"source"`
}
